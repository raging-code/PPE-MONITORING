#!/usr/bin/env python3
"""tools/gen_constants.py: writes constants.h, constants.py and constants.ts from shared/constants.json (design 12.1).
Run: python tools/gen_constants.py. It first checks the constants/settings split against host/config/settings.json and that the
derived times of Profile A reproduce the literals in constants.json exactly. Never edit the generated files by hand."""
import json, os
from fractions import Fraction
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, SETTINGS = 'shared/constants.json', 'host/config/settings.json'
OUT = {'c': 'firmware/components/abi/constants.h', 'py': 'host/ppe_host/constants.py', 'ts': 'dashboard/src/gen/constants.ts'}
HEAD = 'GENERATED by tools/gen_constants.py from shared/constants.json. Do not edit.'
# 12.1 normative key move list (Rev 3.27): host-only keys move to settings.json; these keys are deleted; these firmware keys are added.
MOVED = ('commit_wait_ms', 'checkpoint_max_bytes', 'host_budget_ms', 'dashboard_budget_ms', 'recovering_target_s', 'session_resume_max_min',
         'host_bat_warn_pct', 'host_disk_min_gb', 'task_stall_s', 'supervisor_restart_target_s', 'advisory_heartbeat_s', 'audio_check_interval_s',
         'host_chime_interval_min', 'host_volume_min_pct', 'host_alarm_budget_ms', 'counters_interval_s')
DELETED = ('shift_duration_h', 'retry_buffer_max', 'token_grace_h', 'token_expiry_warn_min', 'sound_check_interval_min', 'sound_check_amber_min',
           'no_audio_alarm_s', 'zero_socket_alarm_s')
FIRMWARE = ('scba_confirm_s', 'scba_confirm_high_co_s', 'scba_response_s', 'resend_wait_ms', 'node_min_send_gap_ms', 'evt_slot_ms', 'evt_jit_ms',
            'beacon_period_s', 'lbt_backoff_min_ms', 'lbt_backoff_max_ms', 'unresolved_pulse_s', 'unresolved_label_s')
# Derived times are multiples of routine_period_s. Each multiplier is the Profile A literal divided by 2, so Profile A gives 15, 15, 60, 5.5, 4.
DERIVED = {'signal_lost_s': Fraction(15, 2), 'link_lost_adverse_s': Fraction(15, 2), 'link_lost_max_s': Fraction(30),
           'shadow_grace_s': Fraction(11, 4), 'beacon_period_s': Fraction(2)}
PERIODS = {'A': 2, 'B': 8}  # Profile B: UNREVIEWED placeholder (design 12.1: review once; the Summary says "about 8 s"). Never the default.
def num(x): x = Fraction(x); return int(x) if x.denominator == 1 else float(x)
def derive(period): return {'routine_period_s': period, **{k: num(m * period) for k, m in DERIVED.items()}}
def load(rel):
    with open(os.path.join(ROOT, rel), encoding='utf8') as f: return json.load(f)
def validate(c, s):
    for k in MOVED:
        if k in c: raise ValueError(f'{k}: host-only key must not be in constants.json')
        if k not in s: raise ValueError(f'{k}: moved key missing from settings.json')
    for k in DELETED:
        if k in c or k in s: raise ValueError(f'{k}: deleted key still present')
    for k in FIRMWARE:
        if k not in c: raise ValueError(f'{k}: firmware key missing from constants.json')
    if set(c) & set(s): raise ValueError('keys in both files: ' + ', '.join(sorted(set(c) & set(s))))
    if c['routine_period_s'] != PERIODS['A']: raise ValueError('routine_period_s is not the Profile A period')
    for k, v in derive(PERIODS['A']).items():
        if c[k] != v or type(c[k]) is not type(v): raise ValueError(f'{k}: Profile A computes {v!r}, constants.json has {c[k]!r}')
def render_c(c):
    o = [f'/* {HEAD} */', '#pragma once'] + [f'#define PPE_{k.upper()} {json.dumps(v)}' for k, v in c.items()]
    return '\n'.join(o + [f'#define PPE_PROFILE_{p}_{k.upper()} {json.dumps(v)}' for p, n in PERIODS.items() for k, v in derive(n).items()] + [''])
def render_py(c):
    o = [f'"""{HEAD}"""'] + [f'{k.upper()} = {v!r}' for k, v in c.items()]
    o += ['CONSTANTS = {  # every key of shared/constants.json'] + [f'    {k!r}: {v!r},' for k, v in c.items()] + ['}', 'PROFILE = "A"  # the values above are Profile A',
          'PROFILES = {  # derived times per profile; B is an unreviewed placeholder']
    return '\n'.join(o + [f'    {p!r}: {derive(n)!r},' for p, n in PERIODS.items()] + ['}', ''])
def render_ts(c):
    return '\n'.join([f'// {HEAD}', 'export const CONSTANTS = ' + json.dumps(c, indent=2) + ' as const;', 'export const PROFILES = ' + json.dumps({p: derive(n) for p, n in PERIODS.items()}, indent=2) + ' as const;', ''])
def render_all(c, s):
    validate(c, s)
    return {OUT['c']: render_c(c), OUT['py']: render_py(c), OUT['ts']: render_ts(c)}
def main():
    c, s = load(SRC), load(SETTINGS)
    for rel, text in render_all(c, s).items():
        p = os.path.join(ROOT, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w', encoding='utf8', newline='\n') as f: f.write(text)
        print('wrote', rel)
    print(f'constants.json: {len(c)} keys, settings.json: {len(s)} keys')
if __name__ == '__main__': main()

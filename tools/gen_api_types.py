#!/usr/bin/env python3
"""tools/gen_api_types.py (P18b): exports api/models.py as shared/ws.schema.json (JSON Schema, WsMessage union)
and shared/openapi.json (OpenAPI 3.1 envelope: components.schemas only, no paths yet -- REST routes are P19),
and generates dashboard/src/gen/ws_messages.ts (one TypeScript interface per $defs entry, Message as the
discriminated union on "type"). Run: python tools/gen_api_types.py. Never edit the three outputs by hand."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'host'))
from ppe_host.api import models as M
OUT = {'schema': 'shared/ws.schema.json', 'openapi': 'shared/openapi.json', 'ts': 'dashboard/src/gen/ws_messages.ts'}
HEAD = 'GENERATED by tools/gen_api_types.py from host/ppe_host/api/models.py. Do not edit.'
PRIM = {'integer': 'number', 'number': 'number', 'string': 'string', 'boolean': 'boolean', 'null': 'null'}

def ts_name(ref):  # "#/$defs/AlertBody" -> "AlertBody"
    return ref.rsplit('/', 1)[-1]

def ts_type(node, defs):
    if '$ref' in node: return ts_name(node['$ref'])
    if 'anyOf' in node: return ' | '.join(ts_type(n, defs) for n in node['anyOf'])
    if 'const' in node: return json.dumps(node['const'])
    if 'enum' in node: return ' | '.join(json.dumps(v) for v in node['enum'])
    t = node.get('type')
    if t == 'array': return ts_type(node.get('items', {}), defs) + '[]'
    if t == 'object' and 'additionalProperties' in node and node['additionalProperties'] not in (True, False):
        return f'Record<string, {ts_type(node["additionalProperties"], defs)}>'
    if t == 'object': return 'Record<string, unknown>'
    return PRIM.get(t, 'unknown')

def render_interface(name, schema, defs):
    required = set(schema.get('required', ()))
    lines = [f'export interface {name} {{']
    for prop, node in schema.get('properties', {}).items():
        opt = '' if prop in required else '?'
        lines.append(f'  {prop}{opt}: {ts_type(node, defs)};')
    lines.append('}')
    return '\n'.join(lines)

def render_ts(ws_schema):
    defs = ws_schema['$defs']
    server_kinds = [n for n, s in defs.items() if 'properties' in s and 'type' in s.get('properties', {})
                    and s['properties']['type'].get('const') and 'srv_seq' in s.get('required', ())]
    client_kinds = [n for n, s in defs.items() if 'properties' in s and 'type' in s.get('properties', {})
                    and s['properties']['type'].get('const') and 'srv_seq' not in s.get('required', ()) and n not in ('ErrorEnvelope',)]
    message_kinds = [n for n in defs if n in server_kinds + client_kinds]
    o = [f'// {HEAD}', '// One interface per host message / shared piece; ServerMessage, ClientMessage and WsMessage are the discriminated unions on "type".', '']
    # stable order: non-message pieces first (alphabetical), then server kinds, then client kinds, each in schema order
    pieces = [n for n in defs if n not in message_kinds]
    for name in pieces:
        o.append(render_interface(name, defs[name], defs)); o.append('')
    for name in server_kinds + client_kinds:
        o.append(render_interface(name, defs[name], defs)); o.append('')
    o.append('export type ServerMessage =\n  ' + ' |\n  '.join(server_kinds) + ';')
    o.append('export type ClientMessage =\n  ' + ' |\n  '.join(client_kinds) + ';')
    o.append('export type WsMessage = ServerMessage | ClientMessage;')
    o.append('')
    o.append(f'export const SCHEMA_VERSION = {M.SCHEMA_VERSION} as const;')
    return '\n'.join(o)

def render_openapi(ws_schema):
    schemas = dict(ws_schema['$defs'])
    return {
        'openapi': '3.1.0',
        'info': {'title': 'PPE Monitoring host API', 'version': str(M.SCHEMA_VERSION),
                  'description': 'WebSocket message and REST error-envelope schemas only (P18b). REST paths are added as P19 and P19c land.'},
        'paths': {},
        'components': {'schemas': schemas},
    }

def main():
    ws_schema = M.WS_ADAPTER.json_schema()
    out = {}
    out[OUT['schema']] = json.dumps(ws_schema, indent=2, sort_keys=False) + '\n'
    out[OUT['openapi']] = json.dumps(render_openapi(ws_schema), indent=2, sort_keys=False) + '\n'
    out[OUT['ts']] = render_ts(ws_schema) + '\n'
    for rel, text in out.items():
        p = os.path.join(ROOT, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w', encoding='utf8', newline='\n') as f: f.write(text)
        print('wrote', rel)

if __name__ == '__main__':
    main()

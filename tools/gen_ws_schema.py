#!/usr/bin/env python3
"""tools/gen_ws_schema.py (P18b): writes shared/ws.schema.json, shared/openapi.json and dashboard/src/gen/ws.ts from host/ppe_host/api/models.py (design 3.13).
Run: python tools/gen_ws_schema.py. The TypeScript is written by the small converter below (no npm package: the dashboard has no package.json before P21); it handles
exactly the JSON Schema keywords Pydantic emits for models.py and raises on any other one, so a new keyword can not be dropped silently. P19 replaces build_openapi()
with app.openapi() once the routes exist; until then openapi.json holds only the error envelope. Never edit the generated files by hand."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'host'))
from ppe_host.api import models as M
OUT = {'ws': 'shared/ws.schema.json', 'openapi': 'shared/openapi.json', 'ts': 'dashboard/src/gen/ws.ts'}
HEAD = 'GENERATED by tools/gen_ws_schema.py from host/ppe_host/api/models.py. Do not edit.'
KEYWORDS = {'$ref', 'additionalProperties', 'anyOf', 'const', 'default', 'enum', 'format', 'items', 'maximum', 'minimum', 'minLength', 'properties', 'required', 'title', 'type'}

def ws_schema(): return M.WS_ADAPTER.json_schema()
def error_schema(ref='#/$defs/{model}'): return M.ErrorEnvelope.model_json_schema(ref_template=ref)
def build_openapi():
    return {'openapi': '3.1.0', 'info': {'title': 'PPE Monitoring host REST API', 'version': str(M.SCHEMA_VERSION)}, 'paths': {},
            'components': {'schemas': {'ErrorEnvelope': error_schema('#/components/schemas/{model}')}}}
def dumps(o): return json.dumps(o, indent=2, ensure_ascii=False) + '\n'

def ts_type(s, where):
    bad = set(s) - KEYWORDS - {'discriminator', 'oneOf', '$defs'}
    if bad: raise ValueError(f'{where}: unsupported JSON Schema keyword {sorted(bad)}')
    if '$ref' in s: return s['$ref'].rsplit('/', 1)[1]
    if 'const' in s: return json.dumps(s['const'])
    if 'enum' in s: return ' | '.join(json.dumps(x) for x in s['enum'])
    if 'anyOf' in s: return ' | '.join(ts_type(x, where) for x in s['anyOf'])
    t = s.get('type')
    if t in ('integer', 'number'): return 'number'
    if t in ('string', 'boolean'): return t
    if t == 'null': return 'null'
    if t == 'array': return '(' + ts_type(s['items'], where) + ')[]' if ('anyOf' in s['items'] or 'enum' in s['items']) else ts_type(s['items'], where) + '[]'
    if t == 'object' and 'properties' not in s:
        ap = s.get('additionalProperties')
        return '{ [key: string]: ' + ('unknown' if ap is True else ts_type(ap, where)) + ' }'
    if t == 'object':
        req = set(s.get('required', []))
        return '{\n' + ''.join(f"  {k}{'' if k in req else '?'}: {ts_type(v, where + '.' + k)};\n" for k, v in s['properties'].items()) + '}'
    raise ValueError(f'{where}: cannot convert {s}')
def render_ts():
    ws, err = ws_schema(), error_schema()
    o = [f'// {HEAD}', f'export const WS_SCHEMA_VERSION = {M.SCHEMA_VERSION} as const;', '']
    for name, s in sorted({**ws['$defs'], 'ErrorEnvelope': err}.items()): o.append(f'export interface {name} ' + ts_type(s, name) + '\n')
    names = lambda ts: [t.__name__ for t in ts]
    for union, ts in (('ServerMessage', M.SERVER_TYPES), ('ClientMessage', M.CLIENT_TYPES)):
        o.append(f'export type {union} =\n' + '\n'.join(f'  | {n}' for n in names(ts)) + ';\n')
    o.append('export type WsMessage = ServerMessage | ClientMessage;\n')
    tag = lambda t: t.model_fields['type'].annotation.__args__[0]
    for const, ts in (('SERVER_TYPES', M.SERVER_TYPES), ('CLIENT_TYPES', M.CLIENT_TYPES)): o.append(f'export const {const} = ' + json.dumps([tag(t) for t in ts]) + ' as const;')
    o.append('export const ALERT_TYPES = ' + json.dumps(list(M.ALERT_TYPES)) + ' as const;')
    o.append('export const ERROR_CODES = ' + json.dumps(list(M.ERROR_CODES)) + ' as const;')
    o.append('export const RETRY_AFTER_CODES = ' + json.dumps(list(M.RETRY_AFTER_CODES)) + ' as const;')
    return '\n'.join(o) + '\n'
def render_all(): return {OUT['ws']: dumps(ws_schema()), OUT['openapi']: dumps(build_openapi()), OUT['ts']: render_ts()}
def main(root=ROOT):
    for rel, text in render_all().items():
        p = os.path.join(root, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w', encoding='utf8', newline='\n') as f: f.write(text)
        print('wrote', rel)
if __name__ == '__main__': main()

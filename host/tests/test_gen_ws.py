"""P18b: tools/gen_ws_schema.py (design 3.13): shared/ws.schema.json, shared/openapi.json and dashboard/src/gen/ws.ts regenerate with an empty diff.
If a generated-file test fails with 'out of date', run: python tools/gen_ws_schema.py Requirements: REQ-API-004, REQ-RUL-001."""
import importlib.util, json, re, sys
from pathlib import Path
import pytest
ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('gen_ws_schema', ROOT / 'tools' / 'gen_ws_schema.py'); gen = importlib.util.module_from_spec(spec)
sys.modules['gen_ws_schema'] = gen; spec.loader.exec_module(gen)
from ppe_host.api import models as M
FILES = gen.render_all()
@pytest.mark.parametrize('rel', sorted(gen.OUT.values()))
def test_generated_file_matches_generator_output(rel):
    p = ROOT / rel
    assert p.exists(), f'{rel} is missing: run python tools/gen_ws_schema.py'
    assert p.read_text(encoding='utf8') == FILES[rel], f'{rel} is out of date: run python tools/gen_ws_schema.py'
def test_generator_is_deterministic(): assert gen.render_all() == gen.render_all()
def test_main_writes_the_three_files(tmp_path):
    gen.main(str(tmp_path))
    for rel, text in FILES.items(): assert (tmp_path / rel).read_text(encoding='utf8') == text
def test_schema_has_all_eleven_messages_in_the_discriminator():
    s = json.loads(FILES[gen.OUT['ws']]); tags = {t.model_fields['type'].annotation.__args__[0] for t in M.SERVER_TYPES + M.CLIENT_TYPES}
    assert s['discriminator']['propertyName'] == 'type' and set(s['discriminator']['mapping']) == tags and len(tags) == 11 and len(s['oneOf']) == 11
    assert len(M.SERVER_TYPES) == 9 and len(M.CLIENT_TYPES) == 2
def test_only_the_client_auth_message_has_a_token_and_no_server_field_is_a_key():
    defs = json.loads(FILES[gen.OUT['ws']])['$defs']
    for name in [t.__name__ for t in M.SERVER_TYPES] + ['NodeSnap', 'AlertBody', 'EpisodeBody', 'Banners', 'RosterRow', 'SessionInfo']:
        for field in defs[name]['properties']: assert not re.search(r'token|secret|cmac|salt|password|(^|_)key($|_)', field), f'{name}.{field}'
    assert 'token' in defs['AuthMsg']['properties'] and 'token' not in defs['HbMsg']['properties']
def test_every_message_in_the_schema_requires_v_and_type_and_forbids_extra_fields():
    defs = json.loads(FILES[gen.OUT['ws']])['$defs']
    for t in M.SERVER_TYPES + M.CLIENT_TYPES:
        d = defs[t.__name__]; assert {'v', 'type'} <= set(d['required']) and d['additionalProperties'] is False, t.__name__
    for t in M.SERVER_TYPES: assert {'srv_seq', 'srv_ts'} <= set(defs[t.__name__]['required']), t.__name__
def test_openapi_has_only_the_error_envelope_until_p19():
    o = json.loads(FILES[gen.OUT['openapi']])
    assert o['openapi'] == '3.1.0' and o['paths'] == {} and list(o['components']['schemas']) == ['ErrorEnvelope']
    assert set(o['components']['schemas']['ErrorEnvelope']['properties']) == {'error_code', 'detail', 'retry_after_s'}
    assert o['components']['schemas']['ErrorEnvelope']['properties']['error_code']['enum'] == list(M.ERROR_CODES)
def test_ts_declares_every_model_and_both_unions():
    ts = FILES[gen.OUT['ts']]
    for name in json.loads(FILES[gen.OUT['ws']])['$defs'] | {'ErrorEnvelope': 0}: assert f'export interface {name} ' in ts, name
    assert re.search(r'export type ServerMessage =\n(  \| \w+Msg\n?){9};', ts) and re.search(r'export type ClientMessage =\n(  \| \w+Msg\n?){2};', ts)
    assert 'export type WsMessage = ServerMessage | ClientMessage;' in ts and ts.startswith('// GENERATED by tools/gen_ws_schema.py')
def test_ts_unions_and_literals_follow_the_schema():
    ts = FILES[gen.OUT['ts']]
    assert 'srv_seq: 0;' in ts and 'epoch: string;' in ts and 'node_id: number | null;' in ts and 'authenticated: 0 | 1;' in ts
    assert 'co_history_30m: { [key: string]: number[][] };' in ts and 'constants: { [key: string]: unknown };' in ts
def test_ts_alert_types_equal_the_catalog_and_the_database_seed():
    cat = json.loads((ROOT / 'shared' / 'alert_catalog.json').read_text(encoding='utf8'))
    seed = re.search(r"INSERT INTO alert_types\(type\) VALUES (.*?);", (ROOT / 'host' / 'migrations' / '0001.sql').read_text(encoding='utf8')).group(1)
    ts_types = json.loads(re.search(r'export const ALERT_TYPES = (\[.*?\]) as const;', FILES[gen.OUT['ts']]).group(1))
    assert ts_types == list(M.ALERT_TYPES) and set(ts_types) == set(re.findall(r"'(\w+)'", seed)) and len(ts_types) == 25 and cat
def test_converter_shapes():
    t = gen.ts_type
    assert t({'anyOf': [{'type': 'integer'}, {'type': 'null'}]}, 'x') == 'number | null'
    assert t({'type': 'array', 'items': {'enum': ['a', 'b']}}, 'x') == '("a" | "b")[]'
    assert t({'type': 'object', 'additionalProperties': True}, 'x') == '{ [key: string]: unknown }'
    assert t({'$ref': '#/$defs/Banners'}, 'x') == 'Banners' and t({'const': 1, 'type': 'integer'}, 'x') == '1'
    assert t({'type': 'object', 'properties': {'a': {'type': 'string'}, 'b': {'type': 'boolean'}}, 'required': ['a']}, 'x') == '{\n  a: string;\n  b?: boolean;\n}'
def test_converter_refuses_a_keyword_it_does_not_know():
    for bad in ({'type': 'string', 'pattern': '^x$'}, {'oneOf': [{'type': 'string'}], 'type': 'string', 'examples': ['x']}):
        with pytest.raises(ValueError, match='unsupported JSON Schema keyword'): gen.ts_type(bad, 'x')
